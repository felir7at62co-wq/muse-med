/** Issue grants for individual workbenches using the current Host account. */
import { createHash } from 'node:crypto'
import { z } from 'zod'
import { readMuseAccountJson } from './account-details.ts'
import { MuseGatewayError, museGatewayOrigin } from './gateway.ts'
import { readMuseSession } from './session.ts'

const tokenPattern = /^[A-Za-z0-9_-]{43}$/u
const grant = z.object({
  code: z.string().regex(tokenPattern),
  expiresIn: z.number().int().positive().max(60),
})

type Audience = 'script-workshop' | 'jingliu'
interface Options {
  baseUrl: string
  sessionFile: string
  requestTimeoutMs: number
  fetcher?: typeof fetch
}

/** Host-only workbench login with the Muse cookie confined to its issuing gateway. */
export class MuseWorkbenchLogin {
  private readonly origin: string

  /** @param options - Account gateway and private session file used by this Host. */
  constructor(private readonly options: Options) {
    this.origin = museGatewayOrigin(options.baseUrl)
  }

  private async session() {
    const stored = await readMuseSession(this.options.sessionFile, this.origin)
    if (!stored) throw new MuseGatewayError('invalid-credentials')
    const id = createHash('sha256').update(JSON.stringify([this.origin, stored.cookie, stored.revision])).digest('hex')
    return { id, cookie: stored.cookie }
  }

  /** @returns A local identifier that changes when the saved Muse session is replaced. */
  async identity(): Promise<string> {
    return (await this.session()).id
  }

  /**
   * Obtain an audience-bound code redeemable by the workbench holding the verifier.
   * @param audience - Workbench registered at the Muse gateway.
   * @param challenge - S256 challenge generated by that workbench.
   * @returns Short-lived grant and the local session identifier used to obtain it.
   */
  async issue(audience: Audience, challenge: string): Promise<{ code: string; expiresIn: number; accountId: string }> {
    if (!tokenPattern.test(challenge)) throw new MuseGatewayError('gateway-rejected')
    const session = await this.session()
    const response = await (this.options.fetcher ?? fetch)(this.origin + '/api/workbench-login/grant', {
      method: 'POST', redirect: 'error', signal: AbortSignal.timeout(this.options.requestTimeoutMs),
      headers: { 'content-type': 'application/json', origin: this.origin, cookie: session.cookie },
      body: JSON.stringify({ audience, challenge }),
    }).catch(() => { throw new MuseGatewayError('gateway-unavailable') })
    if (!response.ok) {
      try { await response.body?.cancel() }
      catch (_error) { /* A disconnected response still has its original HTTP status. */ }
      throw new MuseGatewayError(response.status === 401 ? 'invalid-credentials' : 'gateway-rejected')
    }
    const result = grant.safeParse(await readMuseAccountJson(response))
    if (!result.success || await this.identity() !== session.id) throw new MuseGatewayError('gateway-rejected')
    return { ...result.data, accountId: session.id }
  }
}
