"""平台级默认值。

单独一个模块而不是散在各处写字面量 —— 这些值此前在 **18 个文件**里各写了一遍
`or 5000` / `= 5000` / `default=5000`，改一次默认值得逐个 grep 捞，漏掉一个就会
出现"新建的草稿是 900、大纲直生那条路还是 5000"这种只在某条路径上复现的偏差。
"""
from __future__ import annotations

#: 新建草稿时的每集目标字数（正文 / 小说 / 推文的生成都读它）。
#:
#: 2026-10-23 用户裁定：**5000 → 900**。
#: 短剧一集的实际成片是 1~2 分钟，5000 字对应的是七八分钟的台词量，模型只能靠
#: 灌水凑数（这也是"AI 味"的主要来源之一）。900 字更接近真实短剧的单集体量。
#:
#: ⚠️ 改的是**新建草稿的默认值**，不动已有草稿 —— 用户自己设过的字数是他明确
#: 表达过的意图，不该被一次默认值调整悄悄改掉。已有草稿仍按各自存的
#: `script_drafts.chapter_word_target` 走。
DEFAULT_CHAPTER_WORD_TARGET = 900

#: 允许范围。下限给 1 是为了不挡"我就要写个极短集"的极端需求，
#: 上限 20000 是历史口径（原 Field(5000, ge=1, le=20000)）。
MIN_CHAPTER_WORD_TARGET = 1
MAX_CHAPTER_WORD_TARGET = 20000
