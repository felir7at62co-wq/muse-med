def get_prompt(index: int) -> dict | None:
    """index: 1..25"""
    if 1 <= index <= len(MOCKUPS):
        item = MOCKUPS[index - 1]
        return {
            **item,
            "full_prompt": item["prompt"] + NEGATIVE_TAIL,
        }
    return None


def list_prompts() -> list[dict]:
    """只返回 id/title/category, 不返回完整 prompt (减小 payload)."""
    return [
        {"id": m["id"], "title": m["title"], "category": m["category"]}
        for m in MOCKUPS
    ]


