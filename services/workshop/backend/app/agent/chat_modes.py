_MODE_INDEX = {m["key"]: m for m in CHAT_MODES}


def get_mode_framework(key: str | None) -> str | None:
    """按 key 取隐藏提示词框架; 未知 key / 空 返回 None。"""
    if not key:
        return None
    m = _MODE_INDEX.get(key)
    return m["framework"] if m else None


