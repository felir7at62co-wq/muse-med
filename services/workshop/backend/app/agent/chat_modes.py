def get_mode_generation_note(key: str | None) -> str:
    """取"当前模式"对**生成结果**的写法约定（空模式返回 ""）。

    为什么需要它（2026-09 用户反馈）：
      用户在对话工坊里选了「剧本模式」再点生成，结果毫无变化 —— 因为
      `get_mode_framework` 只被注入到**聊天**的 system prompt
      （见 routes.py 的 `_build_messages` 步骤 1.5），而生成走的是
      `chat_jobs → stages/*.py` 那条确定性流水线，**根本读不到模式**。
      用户因此判定"选择剧本模式也没有用" —— 他的观察是对的。

    与 framework 的**区别**（刻意不复用同一个字符串）：
      framework 是给**聊天里的人工回答**看的，里面写死了 Markdown 输出格式、
      场头模板之类"给用户当场看"的规矩；生成流水线自己有入库格式
      （`drama_principles.storyboard_block()` 等），把 framework 整段塞进去
      只会和它打架。所以这里只取**写法口径**那一句，格式仍归流水线自己管。

    注入位置在 guidance 之后、且明确写着"与用户要求冲突时以用户为准" ——
    模式是用户顺手选的偏好，他那几句具体要求才是他真正在意的东西。
    """
    if not key:
        return ""
    return _GEN_NOTE.get(str(key).strip(), "")


def list_modes_public() -> list[dict]:
    """供前端展示的模式列表(只含 key/label/desc, 不含 framework)。"""
    return [{"key": m["key"], "label": m["label"], "desc": m["desc"]} for m in CHAT_MODES]