"""对话工坊"模式"框架 —— 前端叫「回复方式」。

用户在对话工坊里可以单选一个"模式"(剧本/章节/大纲/角色/分析/头脑风暴...),
选中后, 后端把对应的提示词框架注入到 system prompt 末尾, 引导 AI 用该领域的
专业方法回答。这个框架**不对用户展示**, 仅作为后台上下文。

命名沿革(2026-09): 前端下拉原叫「专业方法」, 用户反馈太抽象——看不出选了会发生
什么, 改叫「回复方式」("我想拿到什么形式的回复")。**key 不动**, 否则历史会话里
存的 mode 值会对不上。
⚠️ 其中 novel / tweet 严格来说不是"回复格式"而是**改写口径**(把原文变成另一种
文体), 它们的 desc 里必须写明这一点, 见各自的注释。

设计要点:
- key: 稳定标识, 前端发送 / 后端匹配
- label: 给用户看的中文短名 (按钮文字)
- desc: 给用户看的一句话说明 (tooltip / 副标题)
- framework: 注入到 system prompt 的隐藏提示词框架 (用户不可见)

新增模式只需在 CHAT_MODES 里加一项即可。
"""
