"""质量内建 —— 把"去 AI 味"从**事后清洗**改成**生成时就不产生**（PLAN §3.2）

## 为什么是"前置"而不是"生成后自动清洗"

两条路的技术权衡（见 PLAN §3.2）：

  路径 A 生成前置：把去味规则编进生成 prompt —— **不增加算力**，一次成型
  路径 B 生成后置：生成完自动接一道 LLM 改写 —— 算力翻倍，且二次改写有损稿风险

选 A 为主。依据是 docs/RESEARCH-去AI感方法论.md 的核心结论之一：

    **"过度清洗会产生新的、更假的指纹。"**

把 B 做成默认强制，等于让每一章都过一次清洗，正好踩这个坑。
所以 B 只作为可选项（现有的「去 AI 味」入口），不做默认。

## 为什么只注入 A 级规则

RESEARCH 的另一条结论是"规则多了会挤压创作空间，可能写出参数化的正确废话"。
所以这里**只注入 A 级**（硬信号、多源一致、可量化）：

  S1 翻案腔        "不是A而是B" / "看似A实则B"
  S2 三连排比抬价  "不仅是…更是…甚至…"
  D1 抽象情绪壳    "心中涌起一股暖流"式，情绪被抽象动词包装
  顿号三连         "A、B、C" 三项并列密度过高

B 级（破折号插入等）**不注入**：它们需要语境判断，写进 prompt 只会让模型
畏手畏脚地回避标点，反而写出不自然的句子。

C 级禁动清单（情绪直说、主角独白多、短段落等）**更不注入** —— 那些是
短剧的类型规范，写进 prompt 会直接损害作品。

## 与「去 AI 味」入口的关系（用户 2026-09-19 明确要求）

内建是**提高默认水位**，不是**限制用户手段**。
所以：去 AI 味 / 精修 / 体检入口**任何情况下都保留**，不按来源做区别对待。
详见 PLAN §3.4 —— 本文档 v2.0 初稿曾写"自产内建、导入后置"的区别对待，已废弃。
"""
from __future__ import annotations

#: 注入生成 prompt 的写作约束。只含 A 级。
#:
#: 措辞原则：写成**正向的写作要求**，而不是"不要做什么"的清单。
#: 原因：模型对"禁止 XX"的遵循度远低于对"应当 YY"的遵循度，而且负面清单越长，
#: 越容易把注意力从故事本身拉走（正是"参数化的正确废话"的成因）。
DEAI_WRITING_RULES = """## 语言质感要求（写的时候就避开，不需要事后清洗）

短剧观众要看的是"人"，不是"文笔"。以下四点是 AI 最容易露馅的地方，写作时直接避开：

1. **不要"翻案腔"**。避免"不是A，而是B""看似A，实则B"这类先否后立的句式成段出现。
   要表达转折，用**人物的动作或对话**去体现，而不是用叙述者下判断。
   例：与其写"他不是害怕，而是在等待时机"，不如写"他攥了攥拳，又松开，退到门边靠着"。

2. **不要三连排比抬价**。避免"不仅是…更是…甚至…"式层层加码，以及"A、B、C"
   三项并列在段落里密集出现。一件事说到位比堆三件更有力。

3. **情绪要落在具体处**。避免"心中涌起一股暖流""一股复杂的情绪蔓延开来"
   这类把情绪交给抽象动词的写法。写**身体反应**或**具体念头**：
   手抖了一下、喉咙发紧、突然想起某句话。情绪**直说**（"她怕了"）没问题，不用回避。

4. **节奏要参差**。爽点处句子压短，情绪链处可以放缓。不要通篇句子一样长、
   段落一样厚 —— 均匀是机器的手感。"""


def build_deai_rules_block(enabled: bool = True) -> str:
    """构造注入用的规则块。

    返回空串表示不注入（调用方据此省掉整段，prompt 里不出现空标题）。

    ⚠ 这个开关**不是给用户调的**。用户 2026-09-19 明确要求：
    "去味规则我们敲定一个最好的方案，不要让用户调强度。"
    它只是给 A/B 验证用的（见下方 verify_note），以及留给将来可能的
    "特殊情况整体关闭"的场景。
    """
    if not enabled:
        return ""
    return DEAI_WRITING_RULES


