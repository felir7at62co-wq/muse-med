def _assemble(intro: str, *chunks: str) -> str:
    """拼成给 LLM 的文本块(去首尾空白)。"""
    body = "\n\n".join(c.strip() for c in chunks if c and c.strip())
    return f"{intro.strip()}\n\n{body}" if intro.strip() else body


def outline_block() -> str:
    """注入大纲生成：主线、节奏与集纲结构。"""
    return _assemble(
        "## 🎯 集纲结构原则（每一集都按此设计，优先级高于文笔）",
        MAINLINE_BODY, PACING_BODY, OUTLINE_DESIGN_BODY, ENDING_HOOK_BODY, LANGUAGE_BODY,
    )


