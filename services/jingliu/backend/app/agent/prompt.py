"""Agent 的系统提示词：工具使用纪律。

## 为什么这份提示词必须强调"不要一次做完"

一次 run 可能 200 轮、派生几十个 job。模型很容易犯两个错：

1. **一口气提交全片出片**。120 镜、几百块、几十分钟。中途任何一个环节错了，
   钱已经花完。所以纪律是"先做 1 镜试片，看过再扩"。
2. **把长任务当同步任务**。提交完 `run_shot_videos` 就以为出片完成了，
   接着去导出 —— 导出的是一堆空镜头。必须 `wait_for_job`。

## 为什么纪律要写成"硬性要求"而不是"建议"

模型对"建议"的遵守率取决于上下文长度。实测同类指令在 20 轮之后基本失效。
所以真正要防的两件事——**余额不够**、**找不回来的操作**——不靠这份提示词，
由代码兜底（见 `policy.py`）。范围、做到哪一步、花钱前要不要问则写在用户的话里，
由模型遵守；它越界的最坏后果被账户余额与版本历史兜住。
"""
