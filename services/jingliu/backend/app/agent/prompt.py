def system_prompt(project_id: str, stage: str = "") -> str:
    # 用户说「明天下午三点提醒我」时要靠它换算；只精确到日，缓存前缀一天内不变。
    today = datetime.now(timezone(timedelta(hours=8))).strftime("%Y-%m-%d %A")
    parts = [SYSTEM, f"\n# 当前项目\n\nproject_id = `{project_id}`\n今天（北京时间）：{today}\n"]
    if stage:
        parts.append(f"当前阶段：{stage}\n")
    return "".join(parts)
