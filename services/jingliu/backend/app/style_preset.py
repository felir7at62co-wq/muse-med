"""生产模式 × 画风预设的**唯一**事实来源（用户 2026-09-09 需求 2/3）。

## 为什么需要它

在此之前，"这部戏长什么样"这件事被硬编码成了**四处互不相干的字面量**：

| 位置 | 原文 |
|---|---|
| `asset_prompt.REALISTIC_STYLE` | 「真人实拍写实风格，电影级摄影质感，高分辨率，」 |
| `asset_prompt._NO_CARTOON` / `_SCENE_REQUIREMENTS` | 「禁止卡通、动漫、插画、3D 渲染风格。」 |
| `jobs._gen_first_frame` | 「电影感分镜首帧，写实摄影质感：」 |
| `jobs._ensure_scene_anchor` | 「电影级场景基准图：」 |
| `look_profile._SYS` 第 2 条 | 「这是一部**现代都市真人实拍剧**」 |

也就是说：**画风分散在四个模块里各写一遍，还带一条自相矛盾的禁令**——
要做动漫剧，光把前缀换成「国漫赛璐璐」是没用的，`_NO_CARTOON` 会同时命令模型
「禁止动漫」，两条一起下发，模型的选择不可预期。所以画风必须整体切换：
前缀、否定项、首帧句、基准图句、影调判定的题面，一次全换。

本模块就是那个整体。任何画风相关的字面量**只允许**出现在这里，
`asset_prompt` / `jobs` / `look_profile` 都只读 `Style` 的字段。

## 与生产模式的关系

`production_mode` 在本项目里的含义是**配音策略**（2026-08 改版，见
`ProjectList.tsx` 的注释）：`drama` 台词长在镜头视频自带音轨里、
`narration` 是我们自己 TTS 合成的旁白。它**不**决定画风。

2026-09-09 起新增 `anime`（动漫剧），配音上按用户决策**沿用真人剧那套**
（音画一体），区别只在画风。所以模式 → 可选画风是一张多对多的表
（`MODE_STYLES`），而不是"一个模式一种画风"。

## 六档现已全部可用

`ENABLED` 是**唯一开关**，与 `character_profile.ENABLED_GENRES` 同款。

- `urban`（都市）：真人剧/解说剧的默认档，2026-09-09 起可用。
- `period`（古风）：古装/仙侠**真人实拍**档。2026-09-19 放开，**必须**与
  `character_profile` 的古装题材联动（见 `ENABLED` 处的说明）。
- `guofeng_3d`（国风3D）：用户 2026-09-18 点名的动漫剧专属画风；它加入
  `ENABLED` 的同时解除了动漫剧模式的置灰（见 `catalog()`）。
- `anime_3d`（3D写实）/ `thick_paint`（厚涂）/ `guoman`（国漫）：
  2026-09-19 一并放开，动漫剧不再有置灰档。

四档放开时**只改了 `ENABLED` 一行**——`Style` 的 11 个字段（`desc` / `prefix` /
`negative` / `frame_head` / `anchor_head` / `video_line` / `texture` /
`scene_texture` / `look_hint`）原先就已逐一写全，正是本模块"画风必须整体切换"
这个设计要的：**词表与开关分离**。

- 前端把全部档位列出来，未启用的灰掉并挂「待完善」徽章；现已无未启用档。
- 后端 `resolve()` 对未启用值一律回退到该模式的已启用默认档，即"存了也不生效"。
  双保险仍然保留：前端禁用只防新建，防不住老库里的脏值、也防不住直接打 API。
  库里的历史脏值（若曾存过未启用档）从今天起会**真的生效**，这是放开的本意。

验收：`backend/scripts/verify_style_presets.py` 逐档钉住目录契约、回退链与
六个注入点的提示词字面（仿 `verify_guofeng_3d.py`）。
"""
from __future__ import annotations

import logging
from dataclasses import dataclass

log = logging.getLogger(__name__)


@dataclass(frozen=True)
class Style:
    """一套画风的全部提示词字面。

    每个字段都对应一个**具体的注入点**，缺一个就会出现"资产图是动漫、
    成片是实拍"这类割裂——正是本模块要消灭的病症。
    """

    key: str
    label: str
    desc: str
    #: 资产图/场景图的开头前缀（原 `asset_prompt.REALISTIC_STYLE`）。
    #: 以「，」结尾：调用点会直接拼接，也会 rstrip("，") 后加句号。
    prefix: str
    #: 画风否定项（原 `_NO_CARTOON`）。**必须与 prefix 同向**：
    #: 真人档禁动漫，动漫档反过来禁真人照片，绝不能两边都禁。
    negative: str
    #: 首帧图提示词的开头（原 jobs 里的「电影感分镜首帧，写实摄影质感：」）
    frame_head: str
    #: 场景基准图提示词的开头（原「电影级场景基准图：」）
    anchor_head: str
    #: 视频提示词里的画风声明。**全参考路线压根没有首帧图**，
    #: 视频模型只看提示词与定妆图，这一句不给就会回到默认实拍。
    video_line: str
    #: 质感兜底词，拼在 `_FORCED` 里的"电影质感"那一段。
    texture: str
    #: 场景图的质感兜底词。与 `texture` 分开：场景句式是
    #: 「…，{scene_texture}，真实材质纹理与光影层次，…」，套人物的
    #: 「电影质感，高清肌理」读起来不通，而动漫档更是连"摄影质感"都不该提。
    scene_texture: str
    #: 给影调判定 LLM 的题面（原 `look_profile._SYS` 里写死的
    #: 「这是一部现代都市真人实拍剧」）。古风剧被按现代都市判影调，
    #: 出来的配方是错的。
    look_hint: str
    #: 定妆图的**布光与镜头规格**（2026-09-21 P1-1/P1-2）。
    #:
    #: ## 为什么加这一层
    #:
    #: 改造前角色图的全部固定模板只有四句（三视图、手位、纯白背景、质量兜底），
    #: 光线这个第一杠杆完全空缺 —— 所有角色图共享一句「光线均匀无投影」，
    #: 那正是「平光 = 廉价感」的教科书定义。
    #:
    #: ## 实测依据（实测 C，`scripts/__ab_assets/C_20260921-104610/`）
    #:
    #: 单变量插入这一段，n=4/组：锐度 285.60±75.20 → **455.15±238.12**。
    #: 增益**集中在有高光可打的材质**（荆棘 295.7→815.0、缎面 369.4→499.3），
    #: 全哑光的粗麻破布几乎没动 —— 是「对部分材质增益大、对其余无害」，
    #: 不是全面提升。
    #:
    #: 关键验证（定妆图必须能当参考图用，中性光是硬需求）：四张 B 组图
    #: **没有任何落地阴影或环境投影**，三视图彼此光照仍一致，动态范围
    #: 175.9→178.3、暗部 p5 26.2→27.4、亮度 SD 56.8→56.2 全部纹丝不动
    #: （既没压暗也没洗白），5500K 没出色偏。
    #:
    #: ⚠️ 布光与镜头是**绑在一起**实测的，数据拆不开各自的贡献；
    #: 别把那 +59% 单独记在光线头上。
    #:
    #: ⚠️ 它与 `asset_prompt._CLEAN_BG` 里的「光线均匀无投影」字面矛盾 ——
    #: **故意保留**：实测通过的就是"两句并存"这个配置，正是它同时拿到了
    #: 「有形体光」与「无投影」。删掉哪一句都是未验证的改动。
    #:
    #: ## 为什么必须按画风分流
    #:
    #: 默认值是摄影棚语言（三点布光 / 柔光箱 / 色温 5500K / 85mm / f5.6），
    #: 它对真人实拍档是对的，但 `guofeng_3d` / `anime_3d` / `thick_paint` /
    #: `guoman` 四档的 `negative` 明写「**禁止真人实拍照片感**」——
    #: 同一条提示词里一边禁实拍、一边报光圈焦距，是**直接自相矛盾**，
    #: 正是本模块开头说的那种"割裂"。
    #:
    #: 非实拍档改用**同样具体、但不带相机术语**的说法：光位/软硬/轮廓光
    #: 这些"可判定的光照约束"才是实测 C 里真正起作用的杠杆，
    #: 而「f/5.6」只是它的摄影外衣，换掉不影响那个杠杆。
    #:
    #: ⚠️ **实测只覆盖了 URBAN/DEFAULT**（A/B/C/E 五批全是这一档），
    #: 所以真人档这两句保持**逐字不变**；其余档位的措辞属于未实测的推断，
    #: 要验请对各档各跑一次 A/B。
    light_spec: str = (
        "布光：影棚三点布光——主光位于相机左前方 45 度、柔光箱柔化，"
        "补光在右侧、强度为主光的一半，背后加一盏轮廓光勾出肩线与发梢；"
        "色温 5500K 中性白，显色均匀，面部无死黑也无过曝高光。"
        "镜头：85mm 中长焦、光圈 f/5.6，全身入画、透视不变形。"
    )
    #: 主动注入的不完美（P1-3）。治「像展示厅不像生活」。
    #:
    #: ⚠️ **这一条没有单独实测过**：实测 A 测的是"质量形容词换成物理描述"，
    #: 是替换不是追加，结论为两者无差别。它是加法，赌的是"可判定的物理细节
    #: 不会伤、可能帮"，由实测 E 的合力验收；若 E 显示变差，第一个摘掉的就是它。
    #:
    #: 默认值含「皮肤保留真实纹理不磨皮」——同样是实拍语言，
    #: 非实拍档要换成该画风自己的"不完美"表达（笔触不均匀 / 材质肌理）。
    imperfection: str = (
        "衣物有自然的穿着褶皱与轻微使用痕迹，发丝不完全服帖，"
        "皮肤保留真实纹理不磨皮。"
    )
    #: 场景参考图的**镜头/视角规格 + 纵深分层**（2026-09-21 P1-2 后半 / P1-4 后半）。
    #:
    #: ## 为什么场景也要单独一层
    #:
    #: 人物侧补了布光与镜头（`light_spec`）之后，场景侧仍然是空的：
    #: `scene_prompt` 的固定模板只有「空镜头/禁人物/禁文字/质量兜底」四段，
    #: **没有焦段、没有景深、没有前中后景**。而检索里"前中后景分层"与
    #: "冷暖对比"正是把画面从"平"拉成"有空间"的两个主要杠杆。
    #:
    #: 焦段取 24–35mm 广角：场景参考图的用途是**交代空间关系**
    #: （哪件陈设在哪一侧，供走位台账引用），长焦会压缩空间、把方位关系压平，
    #: 与 `scene_desc` 第 3 条「主要陈设之间的相对方位」直接冲突。
    #:
    #: ⚠️ 与人物侧同理**必须按画风分流**：非实拍档的 `negative` 写着
    #: 「禁止真人实拍照片感」，给它报 24mm 焦段是自相矛盾。
    #:
    #: ⚠️ **本层未经实测**。人物侧的布光层有实测 C 背书，场景侧没有对应实验
    #: （实测 A/B/C/E 全是人物图）。它是照着同一套道理推的，
    #: 要验请对场景图单跑一次 A/B。
    #:
    #: ⚠️ **前景那句是刻意写"软"的**：场景图的用途是**当参考图交代空间**，
    #: 若强制"前景遮挡"，模型会拿门框/枝叶把空间主体挡掉一大块，
    #: 那就与「完整呈现空间布局」直接对撞，反而毁了这张图的核心用途
    #: （和人物侧"加布光会不会毁掉参考图"是同一类风险）。
    #: 所以写成"可在画面边缘带入"并明写"不遮挡空间主体"，
    #: 要的是**纵深**，不是构图花样。
    #:
    #: 📌 2026-09-21 实测 F（4 组 A/B，`scripts/verify_scene_and_styles_ab.py`）
    #: 的人眼盲评结论：这一段**保留**，但补了最后两句。
    #: 盲评 4 组里 B 赢 2（02 港交所从"死对称 AI 海报"变成真实取景；
    #: 01 废弃水泥厂前景压在两侧、主体完整）、平 1、输 1（04 病房）。
    #: 输的那组和打平那组是**同一个失败模式**：模型为了让出前景而把机位压低拉远，
    #: 空间主体被挤到画面上方，下方四成变成空地板 —— 原文只禁了
    #: "遮挡/占中央"，没禁"把主体挤上去 + 底部留大片空地"，故补之。
    #: ⚠️ 同批的客观数（`depth_lum` 45.9→39.1、锐度 409→349）**不构成**反对证据：
    #: `depth_lum` 量的是上/中/下三带的亮度梯度，不是前中后景分层
    #: ——02a 靠"亮天花板 + 暗反光地面"拿到 33.81，真正有分层的 02b 只有 22.96；
    #: 锐度下降则来自**有意为之**的前景虚化。两个数在这个变量上都失效，
    #: 判决只能来自盲评。
    scene_spec: str = (
        "镜头：24–35mm 广角、光圈 f/8，完整交代空间关系，透视自然不畸变。"
        "画面要有**前景、中景、背景**三层纵深：可在画面边缘带入少量近处实物"
        "（门框边沿、桌角、垂落的织物、枝叶）作为前景参照，"
        "**但不得遮挡空间主体、不得占据画面中央**；"
        "中景是空间主体，背景交代纵深与出口；"
        "三层之间有明确的明暗与冷暖差别，不要压成一个平面。"
        "空间主体必须占据画面中部的主要面积，"
        "不要为了让出前景而把主体挤到画面上方；"
        "画面下方不得留出大片空旷地面（空地板／地毯不超过画面四分之一）。"
    )
    #: **渲染管线与画质规格**，拼在 `video_line` 之后进视频提示词。
    #:
    #: ## 为什么单独一层（用户 2026-10-08 需求）
    #:
    #: 用户实测：在这类 3D 画风的视频提示词里固定拼入一套**渲染管线词**，
    #: 成片质量明显提高 —— DCC/引擎术语（Lumen 全局光照、Nanite 虚拟几何体、
    #: RedshiftRT 光谱光照、路径追踪、次表面散射）把模型从"泛泛的动漫感"
    #: 推向电影级 CG 渲染质感。原先 `texture` 只写到"三维渲染的丝绸、木石与
    #: 青瓷肌理"，比这浅得多。
    #:
    #: ## ⚠️ 只对 **3D/CG 两档**生效（`guofeng_3d` / `anime_3d`），其余四档留空
    #:
    #: 留空 = 与加本字段之前**逐字节相同**，老项目不受影响。不能一刀切给六档：
    #:   · `urban` / `period`（真人实拍）的 `negative` 明写「禁止动漫/3D 渲染风格」，
    #:     再灌引擎渲染词是**直接自相矛盾**；
    #:   · `thick_paint`（厚涂）是笔触绘画语言、`guoman`（国漫）是赛璐璐平涂，
    #:     「Nanite 虚拟几何体」「次表面散射」与它们的美术方向对撞。
    #:
    #: ## ⚠️ 刻意**不含**四类词（用户 2026-10-08 拍板）
    #:
    #: 外部那套提示词模板（「7 大模块」版式）里混着四类**不能固定拼死**的词，
    #: 照抄会与现有机制对撞：
    #:
    #:   ① **画幅 / 帧率**（`16:9`、`24fps`）：画幅由 `VideoRequest.aspect_ratio`
    #:      这个 **API 参数**下发，dev 里 99/100 个项目是竖屏 9:16；
    #:      提示词里写死 16:9 是反向命令。帧率我们控制不了，由通道决定
    #:      （RunningHub 固定 24fps）。写在提示词里只是描述性文字，不生效。
    #:   ② **光线情境**（`自然日光`、`强烈的逆光与丁达尔光效`）：与出品硬规则
    #:      第 10 条（光必须有来源）对撞，且动漫剧的夜戏/室内戏会被强行拉成日光。
    #:      光线**本来就不是全片统一的** —— 见 `look_profile` 模块开头那张表。
    #:   ③ **运动速度**（`利用摄像机缓慢平移`）：规则14条明文禁止
    #:      「缓慢/缓缓」这类词（实测同模型帧间差 40 倍，成片一律慢动作）。
    #:      用户 2026-10-08 裁定：**整句舍弃**，运镜沿用我们原有的方案
    #:      （第 1 条：机位默认固定，有动机才可以动），不从外部模板引入运镜指令。
    #:   ④ **调色**（`青橙对比`）：`look_profile` 的 `palette` 轴已有「青橙对比」、
    #:      `reference` 轴有「好莱坞青橙影调」，是**项目级可编辑**的档位。
    #:      在这里写死会让选了「冷蓝调」的项目收到两条互相矛盾的命令。
    #:
    #: 留下的都是**与剧情、画幅、光线情境无关**的纯渲染规格 —— 这正是它能
    #: "固定拼"而不与任何档案对撞的原因。
    #:
    #: ## 位置：必须进 `video_line`（项目级、三条路径共用）
    #:
    #: 不能写在优化器输出的下游：`run_shot_videos` 有一条快路径
    #: （有预生成稿且无参考图无首帧 → 直接下发预生成稿，不再重新优化），
    #: 下游后处理会把它漏掉 —— 画风当年就是这么丢的，实测命中率 0.1%
    #: （见 `directing_note.project_prompt_context` 的说明）。
    render_line: str = ""


#: ---- 真人实拍档 ----------------------------------------------------------

