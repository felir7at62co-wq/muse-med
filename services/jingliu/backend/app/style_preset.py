#: (画风 key, 时代) → 要替换的字段。不在表里 = 原样（古装剧、其余画风全部不变）。
_ERA_OVERRIDES: dict[tuple[str, str], dict] = {
    ("guofeng_3d", "modern"): _GUOFENG_3D_MODERN,
}


def for_era(st: Style, era: str | None) -> Style:
    """按时代微调画风字面。只有写死了朝代的那档（国风3D）在现代题材下会被换。"""
    ov = _ERA_OVERRIDES.get((st.key, era or ""))
    if not ov:
        return st
    from dataclasses import replace
    return replace(st, **ov)


def era_variants(key: str) -> tuple[str, ...]:
    """某档画风在各时代下的 `video_line`（含原文）。供 `jobs.lock_style_line`
    识别库里"拼的是另一时代那句"的旧提示词并换头。"""
    base = STYLES.get(key)
    if base is None:
        return ()
    out = [base.video_line]
    for (k, _era), ov in _ERA_OVERRIDES.items():
        if k == key and ov.get("video_line") and ov["video_line"] not in out:
            out.append(ov["video_line"])
    return tuple(out)


@dataclass(frozen=True)
class Mode:
    """生产模式 = 配音策略（**不是**画风），外加它允许的画风清单。"""

    key: str
    label: str
    #: 该模式下可选的画风（顺序即前端展示顺序，第一个是默认）
    styles: tuple[str, ...]


#: 模式 → 可选画风。
#:
#: `narration`（解说剧）沿用真人档：它是"实拍画面 + 我们合成的旁白"，
#: 画风需求与真人剧一致。用户只点名了真人剧与动漫剧的风格清单，
#: 解说剧按同为实拍来归档（如需独立清单，改这一行即可）。
MODES: tuple[Mode, ...] = (
    Mode("drama", "真人剧", ("urban", "period")),
    Mode("narration", "解说剧", ("urban", "period")),
    #: 动漫剧：`guofeng_3d` 排第一 = 前端第一个展示、也是该模式默认档
    #: （`default_style` 取"第一个已启用的"）。它启用了，模式即可用。
    Mode("anime", "动漫剧", ("guofeng_3d", "anime_3d", "thick_paint", "guoman")),
    #: 解说剧·角色开口（2026-10-30）：画面可以是实拍也可以是 3D 国漫（首轮实测用的 3D）
    Mode("narration_dlg", "解说剧·角色开口", ("urban", "period", "guofeng_3d", "anime_3d")),
)

BY_MODE: dict[str, Mode] = {m.key: m for m in MODES}


def is_enabled(key: str | None) -> bool:
    return (key or "") in ENABLED


def styles_of(mode: str | None) -> tuple[str, ...]:
    """该模式可选的画风 key。未知模式退回 drama 的清单。"""
    m = BY_MODE.get((mode or "").strip() or "drama") or BY_MODE["drama"]
    return m.styles


def default_style(mode: str | None) -> str:
    """该模式的默认画风：**优先给已启用的那一档**。

    动漫剧三档全部未启用，此时给它自己的第一档（`anime_3d`）作为"标称默认"——
    前端展示用。真正出图时 `resolve()` 仍会因为它未启用而回退到 `urban`，
    两者不矛盾：一个是"这个模式名义上默认哪档"，一个是"实际能生成什么"。
    """
    keys = styles_of(mode)
    for k in keys:
        if is_enabled(k):
            return k
    return keys[0] if keys else DEFAULT.key


def resolve(mode: str | None = None, key: str | None = None) -> Style:
    """(模式, 画风 key) → 实际生效的 `Style`。**永不抛异常、永不返回 None**。

    回退链：不属于该模式 / 未启用 / 未知 / 为空 → 该模式的已启用默认档
    → `DEFAULT`（都市）。

    ⚠️ **必须同时校验"属于该模式"与"已启用"**（2026-09-19 补）：
    原先只查 `is_enabled(k)`，于是 `resolve("anime", "period")` 会返回**古风**
    —— 古风不在动漫剧的清单里，却生效了。以前这条路径被"六档里五档未启用"
    掩盖着（跨模式的组合恰好都落到未启用分支），2026-09-19 放开四档后显形。
    `sanitize()` 入库时本来就挡住跨模式值，所以新数据不会串档；
    这里补的是**老库脏值**与直接打 API 的那条路 —— 与"未启用值也回退"
    同一个理由：不能因为一条脏数据让项目出成另一种画风的片子。

    为什么未启用值也要回退而不是报错：这个函数在出图链路的最里层，
    抛异常等于让一条脏数据阻断整批生成。回退到默认档只是"画风没生效"，
    用户看得见、也能自己改；抛异常则是整个项目生不出图。
    """
    k = (key or "").strip()
    allowed = styles_of(mode)
    if k and k in STYLES and k in allowed:
        if is_enabled(k):
            return STYLES[k]
        # 属于该模式但尚未启用：记一笔，回退到该模式的默认档
        log.info("[style] 画风 %r 尚未启用，本次回退到 %s", k, default_style(mode))
    elif k and k in STYLES and k not in allowed:
        # 跨模式的脏值（老库/直接打 API）：不串档，回退
        log.info("[style] 画风 %r 不属于模式 %r，本次回退到 %s",
                 k, mode, default_style(mode))
    d = default_style(mode)
    if is_enabled(d):
        return STYLES[d]
    return DEFAULT


def load(project_id: str) -> Style:
    """读项目的实际生效画风。读不到一律给 `DEFAULT`（= 改动前行为）。

    与 `look_profile.load` 同款的**同步读库**：画风的注入点在 `jobs` 里有
    多处（首帧、场景基准帧、视频提示词、五处资产图），逐个把参数传下来
    必然漏掉一两处，而漏掉的那条路径出的图就是"画风没生效"的。
    读一行 SQLite 的开销可忽略。
    """
    try:
        from .db import Project, get_session
        with get_session() as session:
            p = session.get(Project, project_id)
            if not p:
                return DEFAULT
            st = resolve(p.production_mode, p.art_style)
            # 时代修正（见 _ERA_OVERRIDES）：与人物档案用同一个判据，
            # 两边不会一个按现代写、一个按古风画。
            from . import era
            return for_era(st, era.project_era(
                p.art_style, p.optimized_script or p.raw_script))
    except Exception as e:                  # noqa: BLE001 画风是增强项，绝不阻断出图
        log.warning("[style] 读取项目画风失败，本次用默认档: %r", e)
        return DEFAULT


def sanitize(mode: str | None, key: str | None) -> str | None:
    """入库前清洗用户传来的画风 key。

    **保留未启用的合法 key**（不改写成 urban）：用户在前端选了"古风"这件事
    本身是有意义的意图记录，等古风放开后无需重新设置。真正的"现在生成什么"
    由 `resolve()` 决定，两者分工明确。

    不合法（不属于该模式、或压根不存在）→ None，即"没设置"。
    """
    k = (key or "").strip()
    if not k:
        return None
    if k not in STYLES:
        return None
    if k not in styles_of(mode):
        return None
    return k


def catalog() -> dict:
    """下发给前端的完整目录（前端**不硬编码**任何画风名与可用性）。

    `enabled=False` 的项前端要**列出但禁用 + 挂「待完善」徽章**（用户决策）：
    看得见规划、点不动，就不会有人建出一个生成结果不对的项目。
    """
    return {
        "modes": [
            {
                "key": m.key,
                "label": m.label,
                # 该模式下有任何一档可用，这个模式才是可用的。动漫剧三档全未启用
                # → 模式本身也禁用，否则用户能建出一个"画风必然回退成实拍"的动漫项目。
                "enabled": any(is_enabled(k) for k in m.styles),
                "default": default_style(m.key),
                "styles": [
                    {
                        "key": k,
                        "label": STYLES[k].label,
                        "desc": STYLES[k].desc,
                        "enabled": is_enabled(k),
                    }
                    for k in m.styles if k in STYLES
                ],
            }
            for m in MODES
        ],
    }
