"""剧本时代判定（现代 / 古装）的**唯一**事实来源（2026-10-19）。

## 为什么单独成一个模块

用户反馈「许多现代剧剧本中却生成了许多古装的人物形象」。查下来是两条独立的路
**都在猜时代、而且猜法互不相干**：

1. `character_profile.infer_genre`：剧本里命中 ≥2 个古装指示词就判古装，
   然后给人物档案的模型明说「本片是**古装**真人实拍风格，不要出现现代妆造词」。
   但那些词在现代剧里俯拾皆是——「格格」来自**格格不入**、「太子」来自
   **狸猫换太子**、「公主」是**小公主**、「太监」是比喻、旗袍唐装现代人也穿。
   dev 库 119 个剧本里 **24 个明显的现代剧被判成古装**（一部有 294 处现代词、
   0 处古装词的都市剧也在其中：命中的是「小公主」「唐装」）。
2. `style_preset.GUOFENG_3D`（动漫剧**默认**画风）的前缀把「国风古风场景、
   中国古典建筑（飞檐斗拱…）」写死在**画风**里——画风本该只管"怎么渲染"，
   却顺带规定了"哪个朝代"，于是现代剧选了动漫剧就整片古风。

两处各自修一遍会再次分裂（档案按现代写、图按古风画），所以时代判定收拢到这里，
两处都只读 `project_era()`。

## 判据

1. **用户选的画风优先**：`urban`（都市）= 现代，`period`（古风）= 古装。
   那是用户明确的选择，剧本里几个词翻不了它。
2. 其余画风（动漫各档）或没选：看剧本。
   - 先剔成语/比喻（`_IDIOMS`），再**按出现次数**计古装分 p 与现代分 m；
   - `p >= 3 且 p > 2m` 才判古装。现代锚点（手机/微信/公司…）是**反证**：
     现代剧随手就是几百处，比喻性的"太监""公主"根本压不过。
   - 仙侠/玄幻词（仙界/剑修/灵石/宗门…）算古装一侧：画面上它们与古装同一套
     服化道。旧词表一个仙侠词都没有，仙侠剧此前是靠「长袍」碰巧凑够 2 个。

拿不准一律判现代：判错成现代的代价是"古装剧的人穿得不够古"（用户一眼能看出、
选「古风」画风即可锁定）；判错成古装则是整片人物穿越，正是这次的事故。

标定：dev 库全部剧本逐个人工核对，见 `scripts/verify_era.py`。
"""
from __future__ import annotations

MODERN = "modern"
PERIOD = "period"

#: 画风 → 时代（用户的显式选择）。不在表里的画风（动漫各档）= 看剧本。
_STYLE_ERA = {"urban": MODERN, "period": PERIOD}

#: 先剔掉的成语与比喻用法。只剔**整串**：「格格不入」剔掉后，真的「格格」
#: （清宫戏）照样计分。
_IDIOMS = ("格格不入", "狸猫换太子", "小公主", "公主病", "公主抱", "公主裙", "白雪公主",
           "公主切", "太子爷", "太子党", "江湖骗子", "老江湖", "江湖救急", "江湖规矩",
           "相忘于江湖", "皇帝的新装", "土皇帝", "太上皇")

#: 古装 / 仙侠一侧。旗袍、唐装、汉服**不收**：现代人日常也穿（婚礼、年会、汉服社），
#: 收进来就是"一件衣服把整部剧打成古装"。
_PERIOD_WORDS = (
    # 宫廷 / 官场
    "皇上", "陛下", "娘娘", "王爷", "将军府", "丞相", "太子", "格格", "公主", "宫女",
    "太监", "朕", "本宫", "臣妾", "奴婢", "微臣", "侯府", "王府", "皇宫", "圣旨",
    "衙门", "县令", "侍卫", "丫鬟", "嬷嬷", "休书", "銮驾", "金銮殿",
    # 江湖
    "客栈", "镖局", "江湖", "掌柜", "少侠", "大侠",
    # 仙侠 / 玄幻
    "仙界", "仙域", "天庭", "仙尊", "仙门", "剑修", "丹修", "灵石", "灵气", "宗门",
    "掌门", "长老", "道友", "渡劫", "飞升", "法宝", "魔尊", "妖兽", "修为", "筑基",
)

#: 现代锚点（反证）。都是古装剧里**不可能**出现的东西。
_MODERN_WORDS = (
    "手机", "微信", "电脑", "电梯", "公司", "总裁", "董事", "汽车", "开车", "豪车",
    "医院", "酒店", "直播", "网络", "视频", "短信", "电话", "机场", "地铁", "别墅",
    "律师", "合同", "咖啡", "高跟鞋", "西装", "朋友圈", "热搜", "股份", "银行卡",
    "微博", "警察", "监控", "外卖", "快递", "出租车", "红绿灯", "办公室", "会议室",
)


def scores(script: str | None) -> tuple[int, int]:
    """(古装分, 现代分)——按出现次数计，先剔成语。供判定与排查日志用。"""
    t = script or ""
    for w in _IDIOMS:
        t = t.replace(w, "")
    p = sum(t.count(w) for w in _PERIOD_WORDS)
    m = sum(t.count(w) for w in _MODERN_WORDS)
    return p, m


def detect(script: str | None) -> str:
    """只看剧本判时代。拿不准判现代（理由见模块头）。"""
    p, m = scores(script)
    return PERIOD if p >= 3 and p > 2 * m else MODERN


def project_era(art_style: str | None, script: str | None) -> str:
    """项目的时代：用户选的画风优先，其余看剧本。**永不抛异常。**"""
    era = _STYLE_ERA.get((art_style or "").strip())
    if era:
        return era
    try:
        return detect(script)
    except Exception:          # noqa: BLE001 判定是增强项，绝不阻断出图
        return MODERN
