"""提示词文本片段：只产出**字符串**，不碰数据库、不碰 LLM、无副作用。

## 为什么单独一个文件

`routes_v2.py` / `jobs.py` 的行数预算是架构守卫里「只许减」的档位
（见 `desktop/scripts/verify-architecture.ts` 的 BUDGETS）。而"某句话该怎么说"
是**纯文本**，与它被拼进哪个流程无关 —— 放在调用点就等于让一段文案长期占用
巨石文件的预算，还会让同一句话在多个调用点各写一份。

这里只放"与人/场景相关的措辞"这一类；框架级硬规则（`_house_rules`）仍留在
`prompt_opt/service.py`，因为它与"读哪份 SKILL 文件、推翻哪几条上游口径"绑在一起。
"""
from __future__ import annotations

#: 单镜在场角色的**稳定处理上限**。超过就要给优化器一段降级提示
#: （逐个锚定位置 / 禁止加人 / 背景人静止）。
#:
#: 依据：上游参考文档 `typical-effect-cases` 第 6.2 节标题即
#: 「4 人及以上：人物站位错乱」，原因栏写"当参考人物超过 4 人时，模型表现不稳定"。
#:
#: ⚠️ 与参考图注入名额（`jobs.refs_cap`）是**两个不同的量**，不要混用：
#: 那边限制"能给模型看几张图"，这边说的是"模型能同时稳定处理几个人"。
CROWD_REF_LIMIT = 4


def crowd_notice(n_chars: int) -> str:
    """超过稳定人数时追加的降级提示；未超过返回空串。

    三条要求各对应一个**已观察到**的退化：

      1. 含糊指代（实测文案里出现过"其他众仙""众人"）—— 要求逐个用场景
         固定陈设锚定位置。这与 `_BLOCKING_REQUIREMENT` 的场景坐标口径一致：
         锚点必须是场景里的实物，不能是"画面左侧"。
      2. 自作主张加背景群众 —— 明文禁止。人数已经到上限时再加人，
         每个人分到的生成预算只会更少。
      3. 给背景人乱加戏 —— 要求静止。

    `n_chars` 由调用方传入而不是自己数：人数的事实来源是
    `jobs._effective_characters`，这里只负责措辞。
    """
    if n_chars <= CROWD_REF_LIMIT:
        return ""
    return (f"\n    ⚠️ 本镜在场角色共 {n_chars} 人，"
            f"**已超过模型稳定处理的 {CROWD_REF_LIMIT} 人**。因此：\n"
            "   1. 每个人的空间位置必须**逐个用场景固定陈设锚定**"
            "（如「X 在火堆东侧」「Y 在白玉阶前左侧」），"
            "不得出现「其他人」「众仙」「众人」这类含糊指代；\n"
            f"   2. **严禁**新增本名单之外的角色（含背景群众）——"
            f"当前人数已经到上限；\n"
            "   3. 其中没有台词也没有主动作的人，保持其位置与姿态**静止**，"
            "不要为其安排动作或反应。")


