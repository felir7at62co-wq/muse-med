def scene_run_header(loc_name: str, k: int, n: int) -> str:
    """同场连续戏的总约束（连续段的第 k/n 镜）。

    ## 为什么需要这一段

    实测项目「912」前 6 镜同属场景「半岛酒店顶楼餐厅」、2-6 镜全标
    `continuous`，注入的场景参考图也是同一张，但每镜的提示词各自把空间
    重新描述了一遍：镜3「豪华高档的豪门会客室」+「大理石茶几」、
    镜4「璀璨水晶吊灯」、镜5「高档餐厅包厢内」—— 连**房间类型和场景名**
    都换了。

    根因：每镜的提示词优化都是**独立**的一次调用，它看不见自己处在一场
    连续戏的中间。参考图管不住这件事——图只钳制"长什么样"，
    文字一旦把餐厅说成会客室，模型按文字走。

    ## 第 3/4 条为什么这么写

    第 3 条（走位延续）在 3.9 之前就存在，用户实测**依然跳变**：它是一句
    **没有事实支撑的空话**——通用句不含位置信息，剧本原文几乎从不写走位，
    段首提示词到第 5 镜早已失真。位置必须是**可传递的显式状态**，
    这才有了走位台账（见 `blocking_continuation`）。

    第 4 条（轴线）是 3.9.1 新增：无解释地越轴会让画面左右关系整体翻转，
    看起来像两个人突然交换了位置。
    """
    return (
        f"【同场连续戏】本镜与前后共 {n} 个镜头同属场景「{loc_name}」，"
        f"本镜是其中第 {k} 镜，**中途没有换景**。因此：\n"
        f"1. 空间类型与场景名必须始终是「{loc_name}」，"
        f"严禁改写成别的房间（如把餐厅写成会客室、客厅、包厢或大堂）；\n"
        f"2. 家具的种类、外观、材质、颜色与摆放位置在全段内完全一致"
        f"（同一张桌子不能一镜是餐桌、下一镜变成大理石茶几），"
        f"灯具、窗户、墙面与光线方向同理；\n"
        f"3. 人物的座次、站位、彼此的朝向与距离延续上一镜结尾，"
        f"不得重新安排走位；本镜只描述**发生了变化**的动作与表情；\n"
        f"4. **机位不得无故换到轴线另一侧**（换了会让画面左右关系整体翻转，"
        f"看起来像两个人突然交换了位置）。确需越轴必须写明动机"
        f"（插入中性镜、人物走动改变视线关系、摄影机连续横移越线）；\n"
        f"5. 不得新增本段前面没有出现过的陈设或装饰。")


def blocking_continuation(prev_order: int, blocking_text: str) -> str:
    """把上一镜的走位台账包成"这是事实"的一段。

    ## 措辞为什么在 2026-09-19 改过

    原文是「本镜**开场画面**必须与之完全一致」——那句字面上要求**机位也一样**，
    而旧格式台账的 `pos` 是画面坐标、参照系正是机位，于是约束**自相矛盾**
    （既要位置一样、又要机位一样，而画面坐标换个机位就翻了）。

    现在把它拆成两句：**空间位置必须一致**（不随取景变）、
    **机位可以换**（但不许为了取景去动人）。并要求道具归属一并延续——
    道具与位置同构：剧本几乎不写"谁拿着什么"，只能靠台账传递。

    `blocking_text` 由调用方渲染（新旧格式两套措辞在那里处理），
    这里不重复判断格式。
    """
    return (f"【上一镜（#{prev_order}）结束时的人物位置】以下是这一镜的"
            f"位置**事实**：\n{blocking_text}\n"
            f"本镜开场时每个人的**空间位置**必须与之一致；"
            f"本镜可以换机位、换景别，但**不得为了配合取景而改变"
            f"任何人的物理位置、朝向或姿态**。"
            f"本镜只描述在此基础上**发生了变化**的位置与姿态；"
            f"没有提到变化的角色一律保持原位、原朝向、**原手持道具**，"
            f"**不得**重新安排座次或走位，**不得**让其中任何人消失或离场。")


def run_recap(recap: str) -> str:
    """段内前情剧本：只为让优化器推断"人此刻在哪"，不是让它重演一遍。"""
    return ("本场戏在本镜之前已经发生的剧本内容（仅用于推断人物此刻的位置、"
            "姿态与状态，**不要**在本镜里重复表演一遍）：\n" + recap)


def run_anchor(anchor_order: int, anchor_prompt: str) -> str:
    """段首镜的画面设定：全段锚到**同一份**文字，而不是一镜接一镜地漂。"""
    return (f"本场戏首镜（#{anchor_order}）已确立的画面设定如下，"
            f"本镜的空间与陈设描写必须与之一致（与本镜原稿冲突时以此为准）：\n"
            + anchor_prompt)
